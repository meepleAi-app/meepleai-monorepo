namespace Api.BoundedContexts.GameManagement.Domain.Entities.SessionSnapshot;

/// <summary>
/// Repository interface for SessionSnapshot persistence.
/// Issue #4755: SessionSnapshot - Delta-based History + State Reconstruction.
/// </summary>
internal interface ISessionSnapshotRepository
{
    Task<SessionSnapshot?> GetByIdAsync(Guid id, CancellationToken cancellationToken = default);
    Task<IReadOnlyList<SessionSnapshot>> GetBySessionIdAsync(Guid sessionId, CancellationToken cancellationToken = default);
    Task<SessionSnapshot?> GetBySessionAndIndexAsync(Guid sessionId, int snapshotIndex, CancellationToken cancellationToken = default);
    Task<SessionSnapshot?> GetLatestBySessionIdAsync(Guid sessionId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Gets snapshots from the nearest checkpoint up to (and including) the target index.
    /// Used for state reconstruction: checkpoint + deltas.
    /// </summary>
    Task<IReadOnlyList<SessionSnapshot>> GetSnapshotsForReconstructionAsync(
        Guid sessionId, int targetIndex, CancellationToken cancellationToken = default);

    Task<int> GetSnapshotCountAsync(Guid sessionId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Counts only auto-generated snapshots for a session.
    /// Issue #5581: Auto-snapshot on Pause — used for cleanup threshold.
    /// </summary>
    Task<int> CountAutoGeneratedBySessionIdAsync(Guid sessionId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Deletes the oldest auto-generated snapshots for a session, keeping at most <paramref name="keepCount"/>.
    /// Manual snapshots are never deleted.
    /// Issue #5581: Auto-snapshot on Pause — cleanup of auto-generated snapshots.
    /// </summary>
    Task DeleteOldestAutoGeneratedAsync(Guid sessionId, int keepCount, CancellationToken cancellationToken = default);

    Task AddAsync(SessionSnapshot snapshot, CancellationToken cancellationToken = default);

    /// <summary>
    /// The snapshot that the event identified by <paramref name="sourceEventId"/> already produced, if any
    /// (the UNIQUE partial index on <c>session_snapshots.source_event_id</c>, CF-2 / #1938). #4848.
    /// </summary>
    Task<SessionSnapshot?> GetBySourceEventIdAsync(Guid sourceEventId, CancellationToken cancellationToken = default);

    /// <summary>
    /// Forgets the snapshots that were added and not saved. After a save that the database refused (the unique
    /// index on the source event), they stay <c>Added</c> on the shared context and the next save would send them
    /// again. #4848.
    /// </summary>
    void DiscardUnsavedAdditions();
}
