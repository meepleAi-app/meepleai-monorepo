using System.Text.Json.Nodes;
using Api.BoundedContexts.GameManagement.Application.Commands.SessionSnapshot;
using Api.BoundedContexts.GameManagement.Domain.Entities.SessionSnapshot;
using Api.BoundedContexts.GameManagement.Infrastructure.Persistence;
using Api.Infrastructure;
using Api.Infrastructure.Entities.GameManagement;
using Api.SharedKernel.Application.Services;
using Api.Tests.Constants;
using FluentAssertions;
using MediatR;
using Microsoft.EntityFrameworkCore;
using Moq;
using Xunit;

namespace Api.Tests.BoundedContexts.GameManagement.Infrastructure;

/// <summary>
/// #4867 — <see cref="SessionSnapshotRepository.DeleteOldestAutoGeneratedAsync"/> prunes by age, but a snapshot is
/// rebuilt from the nearest CHECKPOINT at or before its index (it holds the full state; the checkpoints fall on every
/// tenth index) by applying EVERY delta after it up to its own index, each delta being the difference from the state
/// before. Deleting the oldest snapshots used to delete the checkpoints and leave the deltas built on them (they could
/// not be rebuilt: «no checkpoint found»). Deleting only the checkpoint's neighbours is worse: the rebuild skips a
/// missing delta without complaint and returns a WRONG state. The tests rebuild the state of every snapshot that
/// stays, from real deltas, and compare it with the state it had.
/// </summary>
[Trait("Category", TestCategories.Unit)]
[Trait("BoundedContext", "GameManagement")]
[Trait("Issue", "4852")]
public sealed class SessionSnapshotRepositoryPruningTests
{
    private const int KeepCount = 20;
    private static readonly DateTime Start = new(2026, 11, 4, 12, 0, 0, DateTimeKind.Utc);

    /// <summary>
    /// One in-memory database, opened through a FRESH context for each step, as each request has its own: the
    /// context tracks nothing by default (NoTracking), so reading and deleting the rows through the context that
    /// seeded them would try to attach a second instance of every row.
    /// </summary>
    private sealed class Store
    {
        private readonly DbContextOptions<MeepleAiDbContext> _options = new DbContextOptionsBuilder<MeepleAiDbContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            .ConfigureWarnings(w =>
            {
                w.Ignore(Microsoft.EntityFrameworkCore.Diagnostics.RelationalEventId.PendingModelChangesWarning);
                w.Ignore(Microsoft.EntityFrameworkCore.Diagnostics.InMemoryEventId.TransactionIgnoredWarning);
            })
            .Options;

        private MeepleAiDbContext Open() => new(_options, new Mock<IMediator>().Object, new DomainEventCollector());

        /// <summary>The given indexes as auto-generated snapshots, and the given ones as manual saves.</summary>
        public async Task SeedAsync(Guid sessionId, IEnumerable<int> autoIndexes, params int[] manualIndexes)
        {
            await using var db = Open();
            foreach (var index in autoIndexes)
                db.SessionSnapshots.Add(Snapshot(sessionId, index, SnapshotTrigger.SessionPaused));
            foreach (var index in manualIndexes)
                db.SessionSnapshots.Add(Snapshot(sessionId, index, SnapshotTrigger.ManualSave));
            await db.SaveChangesAsync(TestContext.Current.CancellationToken);
        }

        /// <summary>
        /// The state of the snapshot at <paramref name="index"/> rebuilt as the app does it: the nearest checkpoint,
        /// then every delta after it that the repository returns.
        /// </summary>
        public async Task<string> RebuildAsync(Guid sessionId, int index)
        {
            await using var db = Open();
            var repository = new SessionSnapshotRepository(db, new DomainEventCollector());
            var run = await repository.GetSnapshotsForReconstructionAsync(sessionId, index, TestContext.Current.CancellationToken);
            var state = run[0].DeltaDataJson;
            for (var i = 1; i < run.Count; i++)
                state = JsonDeltaHelper.ApplyDelta(state, run[i].DeltaDataJson);
            return state;
        }

        public async Task PruneAsync(Guid sessionId, int keepCount)
        {
            await using var db = Open();
            var repository = new SessionSnapshotRepository(db, new DomainEventCollector());
            await repository.DeleteOldestAutoGeneratedAsync(sessionId, keepCount, TestContext.Current.CancellationToken);
            await db.SaveChangesAsync(TestContext.Current.CancellationToken);
        }

        public async Task<int[]> IndexesAsync(Guid sessionId)
        {
            await using var db = Open();
            return await db.SessionSnapshots.Where(s => s.SessionId == sessionId)
                .OrderBy(s => s.SnapshotIndex).Select(s => s.SnapshotIndex)
                .ToArrayAsync(TestContext.Current.CancellationToken);
        }
    }

    /// <summary>The state the session had at <paramref name="index"/>: every key written so far is still there.</summary>
    private static string StateAt(int index)
    {
        var state = new JsonObject { ["turn"] = index };
        for (var k = 0; k <= index; k++)
            state[$"k{k}"] = k;
        return state.ToJsonString();
    }

    private static SessionSnapshotEntity Snapshot(Guid sessionId, int index, SnapshotTrigger trigger)
    {
        // As the command stores it: every tenth index is a checkpoint (the full state), the others the delta from the
        // state before.
        var isCheckpoint = SessionSnapshot.ShouldBeCheckpoint(index);
        return new SessionSnapshotEntity
        {
            SessionId = sessionId,
            SnapshotIndex = index,
            TriggerType = (int)trigger,
            TriggerDescription = $"#{index}",
            IsCheckpoint = isCheckpoint,
            DeltaDataJson = isCheckpoint ? StateAt(index) : JsonDeltaHelper.ComputeDelta(StateAt(index - 1), StateAt(index)),
            Timestamp = Start.AddMinutes(index),
        };
    }

    /// <summary>Every snapshot that stays must rebuild to the state it had.</summary>
    private static async Task AssertEveryRemainingSnapshotRebuildsAsync(Store store, Guid sessionId)
    {
        foreach (var index in await store.IndexesAsync(sessionId))
        {
            var rebuilt = JsonNode.Parse(await store.RebuildAsync(sessionId, index));
            JsonNode.DeepEquals(rebuilt, JsonNode.Parse(StateAt(index)))
                .Should().BeTrue($"the snapshot at index {index} must rebuild to its own state, got {rebuilt?.ToJsonString()}");
        }
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_EverySnapshotThatStaysRebuildsToItsOwnState()
    {
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 25));

        await store.PruneAsync(sessionId, KeepCount);

        await AssertEveryRemainingSnapshotRebuildsAsync(store, sessionId);
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_WhenTheOldestAreInTheGroupOfASurvivor_NothingOfThatGroupGoes()
    {
        // 25 auto snapshots, keep 20: by age 0..4 go, but 5..9 stay and are built on the checkpoint 0 and the deltas
        // 1..4. Nothing is deleted: the cap is a minimum.
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 25));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(0, 25));
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_WhenTheCutFallsOnAGroupBoundary_DeletesTheWholeOlderGroup()
    {
        // 30 auto snapshots, keep 20: 0..9 go and nobody in 10..29 needs them.
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 30));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(10, 20));
        await AssertEveryRemainingSnapshotRebuildsAsync(store, sessionId);
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_KeepsTheRunOfAGroupThatStillHasASurvivor_AndDropsTheOlderGroups()
    {
        // 35 auto snapshots, keep 20: 15..34 stay; 15..19 need 10..14 and the checkpoint 10. The group of 0 goes whole.
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 35));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(10, 25));
        await AssertEveryRemainingSnapshotRebuildsAsync(store, sessionId);
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_WhenWholeGroupsFit_KeepsExactlyTheCap()
    {
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 40));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(20, 20));
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_NeverDeletesAManualSnapshot_AndKeepsTheRunItIsBuiltOn()
    {
        // The manual save at index 3 is built on the checkpoint 0 and the deltas 1 and 2, which are AUTO snapshots and
        // among the oldest. Manual snapshots are never deleted, so the run they need stays; 4..9 go.
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 30).Where(i => i != 3), manualIndexes: [3]);

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(10, 20).Prepend(3).Prepend(2).Prepend(1).Prepend(0));
        await AssertEveryRemainingSnapshotRebuildsAsync(store, sessionId);
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_BelowTheCap_DeletesNothing()
    {
        var store = new Store();
        var sessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, KeepCount));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(sessionId)).Should().Equal(Enumerable.Range(0, KeepCount));
    }

    [Fact]
    public async Task DeleteOldestAutoGenerated_LeavesOtherSessionsAlone()
    {
        var store = new Store();
        var sessionId = Guid.NewGuid();
        var otherSessionId = Guid.NewGuid();
        await store.SeedAsync(sessionId, Enumerable.Range(0, 25));
        await store.SeedAsync(otherSessionId, Enumerable.Range(0, 25));

        await store.PruneAsync(sessionId, KeepCount);

        (await store.IndexesAsync(otherSessionId)).Should().Equal(Enumerable.Range(0, 25));
    }
}
