using Api.BoundedContexts.GameManagement.Domain.Entities.SessionSnapshot;
using Api.Infrastructure;
using Api.SharedKernel.Application.Services;
using Api.SharedKernel.Infrastructure;
using Api.Infrastructure.Entities.GameManagement;
using Microsoft.EntityFrameworkCore;

namespace Api.BoundedContexts.GameManagement.Infrastructure.Persistence;

/// <summary>
/// EF Core implementation of ISessionSnapshotRepository.
/// Issue #4755: SessionSnapshot - Delta-based History + State Reconstruction.
/// </summary>
internal sealed class SessionSnapshotRepository : RepositoryBase, ISessionSnapshotRepository
{

    public SessionSnapshotRepository(MeepleAiDbContext dbContext, IDomainEventCollector eventCollector)
        : base(dbContext, eventCollector)
    {
    }

    public async Task<SessionSnapshot?> GetByIdAsync(Guid id, CancellationToken cancellationToken = default)
    {
        var entity = await DbContext.SessionSnapshots
            .AsNoTracking()
            .FirstOrDefaultAsync(s => s.Id == id, cancellationToken)
            .ConfigureAwait(false);

        return entity == null ? null : MapToDomain(entity);
    }

    public async Task<IReadOnlyList<SessionSnapshot>> GetBySessionIdAsync(
        Guid sessionId, CancellationToken cancellationToken = default)
    {
        var entities = await DbContext.SessionSnapshots
            .AsNoTracking()
            .Where(s => s.SessionId == sessionId)
            .OrderBy(s => s.SnapshotIndex)
            .ToListAsync(cancellationToken)
            .ConfigureAwait(false);

        return entities.Select(MapToDomain).ToList();
    }

    public async Task<SessionSnapshot?> GetBySessionAndIndexAsync(
        Guid sessionId, int snapshotIndex, CancellationToken cancellationToken = default)
    {
        var entity = await DbContext.SessionSnapshots
            .AsNoTracking()
            .FirstOrDefaultAsync(s => s.SessionId == sessionId && s.SnapshotIndex == snapshotIndex, cancellationToken)
            .ConfigureAwait(false);

        return entity == null ? null : MapToDomain(entity);
    }

    public async Task<SessionSnapshot?> GetLatestBySessionIdAsync(
        Guid sessionId, CancellationToken cancellationToken = default)
    {
        var entity = await DbContext.SessionSnapshots
            .AsNoTracking()
            .Where(s => s.SessionId == sessionId)
            .OrderByDescending(s => s.SnapshotIndex)
            .FirstOrDefaultAsync(cancellationToken)
            .ConfigureAwait(false);

        return entity == null ? null : MapToDomain(entity);
    }

    public async Task<IReadOnlyList<SessionSnapshot>> GetSnapshotsForReconstructionAsync(
        Guid sessionId, int targetIndex, CancellationToken cancellationToken = default)
    {
        // Find the nearest checkpoint at or before targetIndex
        var checkpointIndex = SessionSnapshot.GetNearestCheckpointIndex(targetIndex);

        var entities = await DbContext.SessionSnapshots
            .AsNoTracking()
            .Where(s => s.SessionId == sessionId
                && s.SnapshotIndex >= checkpointIndex
                && s.SnapshotIndex <= targetIndex)
            .OrderBy(s => s.SnapshotIndex)
            .ToListAsync(cancellationToken)
            .ConfigureAwait(false);

        return entities.Select(MapToDomain).ToList();
    }

    public async Task<int> GetSnapshotCountAsync(
        Guid sessionId, CancellationToken cancellationToken = default)
    {
        return await DbContext.SessionSnapshots
            .CountAsync(s => s.SessionId == sessionId, cancellationToken)
            .ConfigureAwait(false);
    }

    /// <summary>
    /// Issue #5581: Count auto-generated snapshots (SessionPaused, TurnAdvanced, PhaseAdvanced, etc.) — excludes ManualSave.
    /// </summary>
    public async Task<int> CountAutoGeneratedBySessionIdAsync(
        Guid sessionId, CancellationToken cancellationToken = default)
    {
        return await DbContext.SessionSnapshots
            .CountAsync(s => s.SessionId == sessionId
                && s.TriggerType != (int)SnapshotTrigger.ManualSave,
                cancellationToken)
            .ConfigureAwait(false);
    }

    /// <summary>
    /// Issue #5581: Delete oldest auto-generated snapshots exceeding keepCount.
    /// A snapshot is rebuilt from the nearest checkpoint at or before its index by applying EVERY delta up to it (each
    /// delta is the difference from the state before), and the rebuild skips a missing delta without complaint: it
    /// returns a wrong state. So a snapshot that stays needs the whole run from its checkpoint to its own index, and
    /// the run stays even where its snapshots are old enough to go (#4867). The session can then keep up to a
    /// checkpoint interval more than <paramref name="keepCount"/>, per group of indexes that has a snapshot staying.
    /// </summary>
    public async Task DeleteOldestAutoGeneratedAsync(
        Guid sessionId, int keepCount, CancellationToken cancellationToken = default)
    {
        // Every snapshot of the session, the manual ones too: they are never deleted, so they need their run.
        var snapshots = await DbContext.SessionSnapshots
            .Where(s => s.SessionId == sessionId)
            .ToListAsync(cancellationToken)
            .ConfigureAwait(false);

        var autoSnapshots = snapshots
            .Where(s => s.TriggerType != (int)SnapshotTrigger.ManualSave)
            .OrderByDescending(s => s.Timestamp)
            .ToList();

        if (autoSnapshots.Count <= keepCount)
            return;

        var toDelete = autoSnapshots.Skip(keepCount).ToHashSet();

        // Per group of indexes (the group of a checkpoint), the highest index that stays: everything from the
        // checkpoint up to it is needed to rebuild it.
        var highestStayingByGroup = snapshots
            .Where(s => !toDelete.Contains(s))
            .GroupBy(s => SessionSnapshot.GetNearestCheckpointIndex(s.SnapshotIndex))
            .ToDictionary(g => g.Key, g => g.Max(s => s.SnapshotIndex));

        DbContext.SessionSnapshots.RemoveRange(toDelete.Where(s =>
            !(highestStayingByGroup.TryGetValue(SessionSnapshot.GetNearestCheckpointIndex(s.SnapshotIndex), out var highest)
              && s.SnapshotIndex <= highest)));
    }

    public async Task AddAsync(SessionSnapshot snapshot, CancellationToken cancellationToken = default)
    {
        var entity = MapToPersistence(snapshot);
        await DbContext.SessionSnapshots.AddAsync(entity, cancellationToken).ConfigureAwait(false);
    }

    public async Task<SessionSnapshot?> GetBySourceEventIdAsync(
        Guid sourceEventId, CancellationToken cancellationToken = default)
    {
        var entity = await DbContext.SessionSnapshots
            .IgnoreQueryFilters()
            .AsNoTracking()
            .FirstOrDefaultAsync(s => s.SourceEventId == sourceEventId, cancellationToken)
            .ConfigureAwait(false);

        return entity == null ? null : MapToDomain(entity);
    }

    public void DiscardUnsavedAdditions()
    {
        foreach (var entry in DbContext.ChangeTracker.Entries<SessionSnapshotEntity>()
                     .Where(e => e.State == EntityState.Added)
                     .ToList())
        {
            entry.State = EntityState.Detached;
        }
    }

    private static SessionSnapshot MapToDomain(SessionSnapshotEntity entity)
    {
        return new SessionSnapshot(
            entity.Id,
            entity.SessionId,
            entity.SnapshotIndex,
            (SnapshotTrigger)entity.TriggerType,
            entity.TriggerDescription,
            entity.DeltaDataJson,
            entity.IsCheckpoint,
            entity.TurnIndex,
            entity.PhaseIndex,
            entity.CreatedByPlayerId,
            sourceEventId: entity.SourceEventId);
    }

    private static SessionSnapshotEntity MapToPersistence(SessionSnapshot snapshot)
    {
        return new SessionSnapshotEntity
        {
            Id = snapshot.Id,
            SessionId = snapshot.SessionId,
            SnapshotIndex = snapshot.SnapshotIndex,
            TriggerType = (int)snapshot.TriggerType,
            TriggerDescription = snapshot.TriggerDescription,
            DeltaDataJson = snapshot.DeltaDataJson,
            IsCheckpoint = snapshot.IsCheckpoint,
            TurnIndex = snapshot.TurnIndex,
            PhaseIndex = snapshot.PhaseIndex,
            Timestamp = snapshot.Timestamp,
            CreatedByPlayerId = snapshot.CreatedByPlayerId,
            SourceEventId = snapshot.SourceEventId
        };
    }
}
